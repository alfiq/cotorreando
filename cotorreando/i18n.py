_lang = 0


def set_language(code: str) -> None:
    global _lang
    _lang = 1 if code == "en" else 0


def tr(key: str, **kw) -> str:
    text = STRINGS.get(key, (key, key))[_lang]
    return text.format(**kw) if kw else text
